package cmd

import (
	"errors"
	"fmt"
	"io"
	"os"
	"strings"

	"github.com/getkipper/kipper/kip/internal/installer"
	"github.com/getkipper/kipper/kip/internal/issuelink"
)

const errorReportLines = 40

// issueContext supplies install metadata for the issue link and known values
// to redact from the error report. Flags contains names only, without values.
type issueContext struct {
	KipVersion string
	Client     string
	Flags      []string
	Secrets    []string
	Names      []string
}

// installIssueLink returns a prefilled bug report link for an install that
// failed at one of its steps, or "" for any other outcome. Opening the link
// sends it to GitHub, so it holds only values kip controls and no error text.
func installIssueLink(installErr error, ctx issueContext) string {
	var stepErr *installer.StepError
	if !errors.As(installErr, &stepErr) {
		return ""
	}
	repro := "Ran `kip install`"
	if len(ctx.Flags) > 0 {
		repro += " with " + strings.Join(ctx.Flags, " ")
	}
	return issuelink.Report{
		Title:        fmt.Sprintf("kip install failed at %q", stepErr.Step),
		WhatHappened: fmt.Sprintf("`kip install` stopped at the step %q.", stepErr.Step),
		Repro:        repro,
		KipVersion:   ctx.KipVersion,
		Environment:  fmt.Sprintf("kip on %s, server %s, profile %s", ctx.Client, serverDescription(stepErr.Host), plainProfile(stepErr.Profile)),
	}.URL()
}

// installErrorReport returns the last lines of a failed step's error with
// known and recognizable personal data replaced, for the user to read and
// paste into the issue, or "" when no step failed.
func installErrorReport(installErr error, ctx issueContext) string {
	var stepErr *installer.StepError
	if !errors.As(installErr, &stepErr) {
		return ""
	}
	lines := strings.Split(strings.TrimRight(issuelink.Scrub(installErr.Error(), ctx.Secrets, ctx.Names), "\n"), "\n")
	if len(lines) > errorReportLines {
		lines = lines[len(lines)-errorReportLines:]
	}
	return strings.Join(lines, "\n")
}

// installKnownValues collects credentials supplied to or generated by the
// install, cluster and organization names, backup locations, and the local
// home directory for redaction.
func installKnownValues(opts installer.Options, result *installer.Result) (secrets, names []string) {
	secrets = []string{string(opts.BackupRepositoryKey)}
	names = []string{opts.Host, opts.Domain, opts.ConsoleDomain, opts.ConsoleAPIDomain, opts.DexDomain,
		opts.AdminEmail, sshUserEntry(opts.SSHUser), opts.Org, opts.OrgDisplayName}
	if b := opts.BackupStorage; b != nil {
		secrets = append(secrets, b.AccessKeyID, b.SecretAccessKey)
		names = append(names, b.Bucket, b.Endpoint)
	}
	if home, err := os.UserHomeDir(); err == nil {
		names = append(names, home)
	}
	if result != nil {
		secrets = append(secrets, result.AdminPassword, result.GatewayToken)
		names = append(names, result.Domain)
	}
	return secrets, names
}

// reportInstallFailure prints the issue link and saves and prints the error
// report for a failed install step.
func reportInstallFailure(out io.Writer, link, report string) {
	reportFailure(out, "Think this is a Kipper bug? This link opens a GitHub issue form with the step, versions and OS filled in:",
		"install-error", link, report)
}
