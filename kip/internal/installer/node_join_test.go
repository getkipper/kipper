func crictlFailure(desc string) string {
	return `time="2026-10-15T23:55:00Z" level=fatal msg="pulling image: rpc error: ` + desc + `"` + "\n"
}

func probeHost(crictl route) *routedRunner {
	return &routedRunner{routes: []route{{contains: "certs.d/zot.kipper-system.svc.cluster.local:5000/hosts.toml", out: zotMirrorHosts}, crictl}}
}

func TestProbeZotPullPassesOnAMissingManifestFromZot(t *testing.T) {
	worker := probeHost(route{contains: "crictl pull", out: zotProbeNotFound, err: errors.New("exit status 1")})
	require.NoError(t, probeZotPull(worker, "worker-1", "10.43.0.10"))
	assert.True(t, worker.ran("timeout 60 k3s crictl pull 10.43.0.10:5000/kipper-system/node-check:absent"), "the probe is bounded and goes to Zot's ClusterIP only")

	require.NoError(t, probeZotPull(probeHost(route{contains: "crictl pull"}), "worker-1", "10.43.0.10"), "a successful pull passes too")
}

func TestProbeZotPullNeedsTheMirrorToSendToZotFirst(t *testing.T) {
	cases := map[string]string{
		"other endpoint first": strings.Replace(zotMirrorHosts, `[host."https://10.43.0.10`, `[host."https://192.0.2.50:5000/v2"]\n[host."https://10.43.0.10`, 1),
		"no mirror":            "server = \"https://zot.kipper-system.svc.cluster.local:5000/v2\"\n",
	}
	for name, hosts := range cases {
		t.Run(name, func(t *testing.T) {
			worker := &routedRunner{routes: []route{{contains: "hosts.toml", out: hosts}}}
			err := probeZotPull(worker, "worker-1", "10.43.0.10")
			assert.ErrorContains(t, err, "does not send zot.kipper-system.svc.cluster.local:5000 to Zot at 10.43.0.10:5000 first")
			assert.False(t, worker.ran("crictl pull"))
		})
	}
	missing := &routedRunner{routes: []route{{contains: "hosts.toml", out: "cat: No such file or directory", err: errors.New("exit status 1")}}}
	assert.ErrorContains(t, probeZotPull(missing, "worker-1", "10.43.0.10"), "reading the registry mirror")
}

func TestProbeZotPullFailsClosed(t *testing.T) {
	ref := `\"10.43.0.10:5000/kipper-system/node-check:absent\"`
	cases := map[string]string{
		"no resolve hosts": crictlFailure(`code = NotFound desc = failed to pull and unpack image ` + ref + `: failed to resolve reference ` + ref + `: no resolve hosts: not found`),
		"401":              crictlFailure(`code = Unknown desc = failed to pull and unpack image ` + ref + `: failed to resolve reference ` + ref + `: unexpected status from HEAD request to https://10.43.0.10:5000/v2/kipper-system/node-check/manifests/absent: 401 Unauthorized`),
		"x509":             crictlFailure(`code = Unknown desc = failed to pull and unpack image ` + ref + `: failed to resolve reference ` + ref + `: tls: failed to verify certificate: x509: certificate signed by unknown authority`),
		"i/o timeout":      crictlFailure(`code = Unknown desc = failed to pull and unpack image ` + ref + `: failed to resolve reference ` + ref + `: dial tcp 10.43.0.10:5000: i/o timeout`),
		"timed out":        "",
	}
	for name, out := range cases {
		t.Run(name, func(t *testing.T) {
			worker := probeHost(route{contains: "crictl pull", out: out, err: errors.New("exit status 1")})
			err := probeZotPull(worker, "worker-1", "10.43.0.10")
			require.Error(t, err)
			assert.Contains(t, err.Error(), "worker-1")
			assert.Contains(t, err.Error(), "/var/lib/rancher/k3s/agent/containerd/containerd.log")
			if out != "" {
				assert.Contains(t, err.Error(), strings.SplitN(out, "\n", 2)[0])
			}
		})
	}
}

