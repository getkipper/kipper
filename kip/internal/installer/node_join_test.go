func TestOpenWorkerForChecksKeepsWorkloadsAndReplicasOff(t *testing.T) {
	master := &routedRunner{routes: []route{{contains: "instancemanagers.longhorn.io", out: "running "}}}
	require.NoError(t, openWorkerForChecks(master, "worker-1", fastJoin))

	index := func(substring string) int {
		for i, c := range master.commands {
			if strings.Contains(c, substring) {
				return i
			}
		}
		return -1
	}
	replicasOff := index(`nodes.longhorn.io worker-1 --type merge -p '{"spec":{"allowScheduling":false}}'`)
	tainted := index("kubectl taint nodes worker-1 " + checkingTaint + "=true:NoSchedule --overwrite")
	uncordoned := index("kubectl uncordon worker-1")
	waited := index(`instancemanagers.longhorn.io -o jsonpath='{range .items[?(@.spec.nodeID=="worker-1")]}`)
	require.NotEqual(t, -1, replicasOff, "replica scheduling is disabled")
	require.NotEqual(t, -1, tainted, "the taint keeps ordinary pods off")
	require.NotEqual(t, -1, uncordoned)
	require.NotEqual(t, -1, waited, "the instance manager is waited for")
	assert.Less(t, replicasOff, uncordoned)
	assert.Less(t, tainted, uncordoned)
	assert.Less(t, uncordoned, waited)
}

