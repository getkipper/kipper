var fastJoin = joinTimeouts{ready: 20 * time.Millisecond, validation: 20 * time.Millisecond, schedulable: 20 * time.Millisecond, interval: time.Millisecond}

func TestWaitForWorkerStorageNeedsTheNodeAndLonghornReady(t *testing.T) {
	ok := []route{
		{contains: "get node worker-1", out: "True"},
		{contains: "app=longhorn-manager", out: "true "},
		{contains: "app=longhorn-csi-plugin", out: "true true true "},
		{contains: "longhorn.io/component=engine-image", out: "true "},
	}
	require.NoError(t, waitForWorkerStorage(&routedRunner{routes: ok}, "worker-1", fastJoin))

	noEngine := append([]route{{contains: "longhorn.io/component=engine-image", out: ""}}, ok...)
	assert.ErrorContains(t, waitForWorkerStorage(&routedRunner{routes: noEngine}, "worker-1", fastJoin), "Longhorn engine image has not started on worker-1")

	notReady := append([]route{{contains: "app=longhorn-csi-plugin", out: "true false true "}}, ok...)
	assert.ErrorContains(t, waitForWorkerStorage(&routedRunner{routes: notReady}, "worker-1", fastJoin), "longhorn-csi-plugin is not ready on worker-1")

	missing := append([]route{{contains: "app=longhorn-manager", out: ""}}, ok...)
	assert.ErrorContains(t, waitForWorkerStorage(&routedRunner{routes: missing}, "worker-1", fastJoin), "longhorn-manager has not started")

	down := append([]route{{contains: "get node worker-1", out: "False"}}, ok...)
	assert.ErrorContains(t, waitForWorkerStorage(&routedRunner{routes: down}, "worker-1", fastJoin), "worker-1 is not Ready")
}

func TestValidationManifestPinsThePodAndUsesALonghornVolume(t *testing.T) {
	docs := strings.Split(validationManifest("worker-1", "abc123", "10.42.0.5"), "\n---\n")
	require.Len(t, docs, 2)
	var pvc, pod map[string]any
	require.NoError(t, yaml.Unmarshal([]byte(docs[0]), &pvc))
	require.NoError(t, yaml.Unmarshal([]byte(docs[1]), &pod))
	assert.Equal(t, "longhorn-single", pvc["spec"].(map[string]any)["storageClassName"])
	spec := pod["spec"].(map[string]any)
	assert.Equal(t, "worker-1", spec["nodeName"], "nodeName bypasses the cordon")
	script := spec["containers"].([]any)[0].(map[string]any)["command"].([]any)[2].(string)
	assert.Contains(t, script, "nslookup kubernetes.default.svc.cluster.local 10.42.0.5")
	assert.Contains(t, script, `[ "$(cat /data/check)" = kipper ]`)
	assert.Equal(t, validationName("worker-1", "abc123"), pod["metadata"].(map[string]any)["name"])
	assert.Equal(t, validationNodeHash("worker-1"), pod["metadata"].(map[string]any)["labels"].(map[string]any)[validationLabel])
	assert.LessOrEqual(t, len(validationName(strings.Repeat("a", 253), "abc123")), 63)
}

func validationHosts(podPhase, logs string) (*routedRunner, *routedRunner) {
	master := &routedRunner{routes: []route{
		{contains: "k8s-app=kube-dns", out: "10.42.0.5"},
		{contains: "jsonpath='{.status.phase}'", out: podPhase},
		{contains: "kubectl -n kube-system logs", out: logs},
		{contains: "get events", out: "FailedMount: attach timed out\n"},
		{contains: "/proxy/healthz", out: "ok"},
	}}
	worker := &routedRunner{routes: []route{
		{contains: "-K /dev/stdin", out: "200"},
		{contains: "/v2/", out: "401"},
		{contains: "hosts.toml", out: zotMirrorHosts},
		{contains: "crictl pull", out: zotProbeNotFound, err: errors.New("exit status 1")},
	}}
	return master, worker
}

