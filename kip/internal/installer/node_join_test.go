// failingFirst fails the first count commands containing substring, then
// answers from its routes.
type failingFirst struct {
	routedRunner
	substring string
	count     int
}

func (f *failingFirst) Run(command string) (string, error) {
	if strings.Contains(command, f.substring) && f.count > 0 {
		f.count--
		f.commands = append(f.commands, command)
		return "", errors.New(`exit status 1: Error from server (Forbidden): admission webhook "validator.longhorn.io" denied the request: spec and status of disks on node worker-1 are being syncing and please retry later.`)
	}
	return f.routedRunner.Run(command)
}

func TestLonghornSchedulingChangesWaitForTheDisksToSync(t *testing.T) {
	master := &failingFirst{routedRunner: routedRunner{routes: []route{{contains: "instancemanagers.longhorn.io", out: "running "}}}, substring: "allowScheduling", count: 2}
	require.NoError(t, openWorkerForChecks(master, "worker-1", joinTimeouts{ready: time.Second, validation: time.Second, schedulable: time.Second, interval: time.Millisecond}))

	master = &failingFirst{routedRunner: routedRunner{routes: []route{{contains: "nodes.longhorn.io worker-1 -o jsonpath", out: "True"}}}, substring: "allowScheduling", count: 2}
	require.NoError(t, uncordonWorker(master, "worker-1", joinTimeouts{ready: time.Second, validation: time.Second, schedulable: time.Second, interval: time.Millisecond}))

	master = &failingFirst{substring: "allowScheduling", count: 1000}
	assert.ErrorContains(t, openWorkerForChecks(master, "worker-1", fastJoin), "please retry later", "the last refusal is reported")
	assert.False(t, master.ran("kubectl uncordon"))
}

