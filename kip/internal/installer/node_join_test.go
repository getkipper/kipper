func TestRemoveTaintCommandSucceedsOnlyWhenTheTaintIsGone(t *testing.T) {
	cases := []struct {
		name          string
		removeStatus  int
		readStatus    int
		taints        string
		wantSucceeded bool
	}{
		{name: "removed", removeStatus: 0, readStatus: 0, taints: "other", wantSucceeded: true},
		{name: "already absent", removeStatus: 1, readStatus: 0, taints: "", wantSucceeded: true},
		{name: "a similar key stays", removeStatus: 1, readStatus: 0, taints: checkingTaint + "-extra", wantSucceeded: true},
		{name: "still there", removeStatus: 1, readStatus: 0, taints: "other " + checkingTaint, wantSucceeded: false},
		{name: "unreadable", removeStatus: 1, readStatus: 1, taints: "", wantSucceeded: false},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			dir := t.TempDir()
			kubectl := fmt.Sprintf("#!/bin/sh\ncase \"$1\" in taint) exit %d ;; get) printf '%%s' '%s'; exit %d ;; esac\nexit 2\n", c.removeStatus, c.taints, c.readStatus)
			//nolint:gosec // G306: the stand-in kubectl must be executable to run from PATH.
			require.NoError(t, os.WriteFile(filepath.Join(dir, "kubectl"), []byte(kubectl), 0o700))
			cmd := exec.Command("sh", "-c", removeTaintCommand("worker-1", checkingTaint))
			cmd.Env = append(os.Environ(), "PATH="+dir+":/usr/bin:/bin")
			err := cmd.Run()
			assert.Equal(t, c.wantSucceeded, err == nil, "exit: %v", err)
		})
	}
}

