func TestGetRouteDNSStatus(t *testing.T) {
	originalLookup := lookupHost
	t.Cleanup(func() { lookupHost = originalLookup })

	clusterIP := "203.0.113.42"
	otherIP := "198.51.100.7"

	node := &corev1.Node{
		ObjectMeta: metav1.ObjectMeta{Name: "node-1"},
		Status: corev1.NodeStatus{
			Addresses: []corev1.NodeAddress{
				{Type: corev1.NodeExternalIP, Address: clusterIP},
			},
		},
	}

	tests := []struct {
		name        string
		host        string
		clusterDom  string
		lookupAddrs []string
		lookupErr   error
		wantStatus  string
	}{
		{
			name:        "ok when DNS resolves to cluster IP",
			host:        "example.com",
			clusterDom:  "kipper.run",
			lookupAddrs: []string{clusterIP},
			wantStatus:  dnsStatusOK,
		},
		{
			name:        "mismatch when DNS resolves elsewhere",
			host:        "example.com",
			clusterDom:  "kipper.run",
			lookupAddrs: []string{otherIP},
			wantStatus:  dnsStatusMismatch,
		},
		{
			name:       "unresolved when lookup errors",
			host:       "example.com",
			clusterDom: "kipper.run",
			lookupErr:  fmt.Errorf("no such host"),
			wantStatus: dnsStatusUnresolved,
		},
		{
			name:       "gateway for kipper.run subdomains",
			host:       "myapp-test-203-0-113-42.kipper.run",
			clusterDom: "example.com",
			wantStatus: dnsStatusGateway,
		},
		{
			name:       "wildcard for subdomains of the operator's cluster domain",
			host:       "myapp.example.com",
			clusterDom: "example.com",
			wantStatus: dnsStatusWildcard,
		},
		{
			name:       "kipper.run takes precedence over a kipper.run-based cluster domain",
			host:       "myapp-foo.kipper.run",
			clusterDom: "foo.kipper.run",
			wantStatus: dnsStatusGateway,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			lookupHost = func(string) ([]string, error) { return tt.lookupAddrs, tt.lookupErr }

			app := &kipperv1.App{
				ObjectMeta: metav1.ObjectMeta{Name: "web", Namespace: "default"},
				Spec: kipperv1.AppSpec{
					Image: "nginx", Port: 80, Replicas: int32Ptr(1),
					Route: &kipperv1.AppRoute{Host: tt.host, Path: "/"},
				},
			}
			handler := &Apps{
				Client:   fake.NewClientset(node),
				CRClient: testCRClient(app),
				Domain:   tt.clusterDom,
			}

			r := chi.NewRouter()
			r.Get("/projects/{name}/apps/{app}/route/dns-status", handler.GetRouteDNSStatus)

			req := httptest.NewRequest("GET", "/projects/default/apps/web/route/dns-status", nil)
			rec := httptest.NewRecorder()
			r.ServeHTTP(rec, req)

			assert.Equal(t, http.StatusOK, rec.Code, "body: %s", rec.Body.String())

			var resp dnsStatusResponse
			_ = json.Unmarshal(rec.Body.Bytes(), &resp)
			assert.Equal(t, tt.wantStatus, resp.Status, "message: %s", resp.Message)
			if tt.wantStatus == dnsStatusOK || tt.wantStatus == dnsStatusMismatch || tt.wantStatus == dnsStatusUnresolved {
				assert.Equal(t, []string{clusterIP}, resp.ExpectedIPs)
			}
		})
	}
}

func TestGetRouteDNSStatus_VerifyForcesLookupForWildcard(t *testing.T) {
	originalLookup := lookupHost
	t.Cleanup(func() { lookupHost = originalLookup })
	lookupHost = func(string) ([]string, error) { return []string{"203.0.113.42"}, nil }

	node := &corev1.Node{
		ObjectMeta: metav1.ObjectMeta{Name: "node-1"},
		Status: corev1.NodeStatus{
			Addresses: []corev1.NodeAddress{
				{Type: corev1.NodeExternalIP, Address: "203.0.113.42"},
			},
		},
	}
	app := &kipperv1.App{
		ObjectMeta: metav1.ObjectMeta{Name: "web", Namespace: "default"},
		Spec: kipperv1.AppSpec{
			Image: "nginx", Port: 80, Replicas: int32Ptr(1),
			Route: &kipperv1.AppRoute{Host: "myapp.example.com", Path: "/"},
		},
	}
	handler := &Apps{
		Client:   fake.NewClientset(node),
		CRClient: testCRClient(app),
		Domain:   "example.com",
	}

	r := chi.NewRouter()
	r.Get("/projects/{name}/apps/{app}/route/dns-status", handler.GetRouteDNSStatus)

	req := httptest.NewRequest("GET", "/projects/default/apps/web/route/dns-status?verify=true", nil)
	rec := httptest.NewRecorder()
	r.ServeHTTP(rec, req)

	assert.Equal(t, http.StatusOK, rec.Code)
	var resp dnsStatusResponse
	_ = json.Unmarshal(rec.Body.Bytes(), &resp)
	assert.Equal(t, dnsStatusOK, resp.Status, "verify=true must bypass the wildcard short-circuit")
}

