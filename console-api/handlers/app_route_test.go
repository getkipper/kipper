func routeRouter(handler *Apps) *chi.Mux {
	r := chi.NewRouter()
	r.Route("/projects/{name}/apps/{app}", func(r chi.Router) {
		r.Get("/route", handler.GetRoute)
		r.Put("/route", handler.SetRoute)
		r.Delete("/route", handler.DeleteRoute)
	})
	return r
}

