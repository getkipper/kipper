func TestSetRoute_RedirectFromRoundTrips(t *testing.T) {
	app := &kipperv1.App{
		ObjectMeta: metav1.ObjectMeta{Name: "web", Namespace: "default"},
		Spec:       kipperv1.AppSpec{Image: "nginx", Port: 80, Replicas: int32Ptr(1)},
	}
	crClient := testCRClient(app)
	handler := &Apps{Client: fake.NewClientset(), CRClient: crClient}

	body := `{"host":"example.com","redirect_from":[" www.example.com ","","old.example.net"]}`
	req := httptest.NewRequest("PUT", "/projects/default/apps/web/route", strings.NewReader(body))
	rec := httptest.NewRecorder()
	routeRouter(handler).ServeHTTP(rec, req)

	assert.Equal(t, http.StatusOK, rec.Code)
	var resp routeResponse
	_ = json.Unmarshal(rec.Body.Bytes(), &resp)
	assert.Equal(t, []string{"www.example.com", "old.example.net"}, resp.RedirectFrom,
		"entries are trimmed and blanks dropped")

	var updated kipperv1.App
	_ = crClient.Get(context.Background(), crclient.ObjectKey{Namespace: "default", Name: "web"}, &updated)
	assert.Equal(t, []string{"www.example.com", "old.example.net"}, updated.Spec.Route.RedirectFrom)

	// A follow-up save without the field clears the list, matching the
	// full-state semantics of host and path.
	req = httptest.NewRequest("PUT", "/projects/default/apps/web/route", strings.NewReader(`{"host":"example.com"}`))
	rec = httptest.NewRecorder()
	routeRouter(handler).ServeHTTP(rec, req)
	assert.Equal(t, http.StatusOK, rec.Code)
	_ = crClient.Get(context.Background(), crclient.ObjectKey{Namespace: "default", Name: "web"}, &updated)
	assert.Empty(t, updated.Spec.Route.RedirectFrom)
}

func TestSetRoute_RedirectFromOverLimitRejected(t *testing.T) {
	app := &kipperv1.App{
		ObjectMeta: metav1.ObjectMeta{Name: "web", Namespace: "default"},
		Spec:       kipperv1.AppSpec{Image: "nginx", Port: 80, Replicas: int32Ptr(1)},
	}
	crClient := testCRClient(app)
	handler := &Apps{Client: fake.NewClientset(), CRClient: crClient}

	hosts := make([]string, kipperv1.MaxRedirectFromHosts+1)
	for i := range hosts {
		hosts[i] = fmt.Sprintf("alias-%d.example.com", i)
	}
	body, _ := json.Marshal(map[string]interface{}{"host": "example.com", "redirect_from": hosts})
	req := httptest.NewRequest("PUT", "/projects/default/apps/web/route", strings.NewReader(string(body)))
	rec := httptest.NewRecorder()
	routeRouter(handler).ServeHTTP(rec, req)

	assert.Equal(t, http.StatusBadRequest, rec.Code)
	assert.Contains(t, rec.Body.String(), "redirect domains")

	var updated kipperv1.App
	_ = crClient.Get(context.Background(), crclient.ObjectKey{Namespace: "default", Name: "web"}, &updated)
	assert.Nil(t, updated.Spec.Route, "a rejected request must not partially update the route")
}

