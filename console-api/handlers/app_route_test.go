// An App with Spec.Route set but Host empty (created by direct CR apply
// before the API filled it in) still has a real effective host derived
// from CLUSTER_DOMAIN. GetRoute must surface that derived host so the
// Settings tab matches the Routes page.
func TestGetRoute_ImplicitHostDerivedFromDomain(t *testing.T) {
	ns := &corev1.Namespace{
		ObjectMeta: metav1.ObjectMeta{
			Name:   "team-test",
			Labels: map[string]string{"kipper.run/environment": "test"},
		},
	}
	app := &kipperv1.App{
		ObjectMeta: metav1.ObjectMeta{Name: "web", Namespace: "team-test"},
		Spec: kipperv1.AppSpec{
			Image: "nginx", Port: 80, Replicas: int32Ptr(1),
			// Host omitted — must be derived from the cluster domain.
			Route: &kipperv1.AppRoute{Path: "/"},
		},
	}
	handler := &Apps{
		Client:   fake.NewClientset(ns),
		CRClient: testCRClient(app),
		Domain:   "kipper.run",
	}

	req := httptest.NewRequest("GET", "/projects/team-test/apps/web/route", nil)
	rec := httptest.NewRecorder()
	routeRouter(handler).ServeHTTP(rec, req)

	assert.Equal(t, http.StatusOK, rec.Code)
	var resp routeResponse
	_ = json.Unmarshal(rec.Body.Bytes(), &resp)
	assert.True(t, resp.Enabled)
	assert.Equal(t, "web-test.kipper.run", resp.Host)
	assert.Equal(t, "https://web-test.kipper.run/", resp.URL)
}

