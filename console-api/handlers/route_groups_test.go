func TestRouteGroups_Create_NormalizesPath(t *testing.T) {
	frontend := &kipperv1.App{
		ObjectMeta: metav1.ObjectMeta{Name: "frontend", Namespace: "default"},
		Spec:       kipperv1.AppSpec{Image: "nginx", Port: 80, Replicas: int32Ptr(1)},
	}
	api := &kipperv1.App{
		ObjectMeta: metav1.ObjectMeta{Name: "api", Namespace: "default"},
		Spec:       kipperv1.AppSpec{Image: "api:v1", Port: 8080, Replicas: int32Ptr(1)},
	}
	crClient := testCRClient(frontend, api)
	handler := &RouteGroups{Client: fake.NewClientset(), CRClient: crClient}

	// A stray leading space and a missing leading slash — both easy to type
	// by hand — must be cleaned before they reach the route.
	body := `{"host":"app.example.com","mappings":[{"path":" /","app":"frontend"},{"path":"backend/","app":"api"}]}`
	req := httptest.NewRequest("POST", "/projects/default/route-groups", strings.NewReader(body))
	rec := httptest.NewRecorder()
	rgRouter(handler).ServeHTTP(rec, req)

	assert.Equal(t, http.StatusOK, rec.Code)

	var updatedFrontend kipperv1.App
	_ = crClient.Get(context.Background(), crclient.ObjectKey{Namespace: "default", Name: "frontend"}, &updatedFrontend)
	assert.Equal(t, "/", updatedFrontend.Spec.Route.Path)

	var updatedAPI kipperv1.App
	_ = crClient.Get(context.Background(), crclient.ObjectKey{Namespace: "default", Name: "api"}, &updatedAPI)
	assert.Equal(t, "/backend/", updatedAPI.Spec.Route.Path)

	// The response must echo the normalized paths, not the raw request,
	// so API callers see the canonical state that was actually stored.
	var resp routeGroupResult
	_ = json.Unmarshal(rec.Body.Bytes(), &resp)
	paths := map[string]string{}
	for _, m := range resp.Mappings {
		paths[m.App] = m.Path
	}
	assert.Equal(t, "/", paths["frontend"])
	assert.Equal(t, "/backend/", paths["api"])
}

