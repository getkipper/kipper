func TestRouteGroups_Update_AddsAndRemovesMappings(t *testing.T) {
	frontend := &kipperv1.App{
		ObjectMeta: metav1.ObjectMeta{Name: "frontend", Namespace: "default"},
		Spec: kipperv1.AppSpec{
			Image: "nginx", Port: 80, Replicas: int32Ptr(1),
			Route: &kipperv1.AppRoute{Host: "app.example.com", Path: "/"},
		},
	}
	oldAPI := &kipperv1.App{
		ObjectMeta: metav1.ObjectMeta{Name: "old-api", Namespace: "default"},
		Spec: kipperv1.AppSpec{
			Image: "api:v1", Port: 8080, Replicas: int32Ptr(1),
			Route: &kipperv1.AppRoute{Host: "app.example.com", Path: "/api"},
		},
	}
	newAPI := &kipperv1.App{
		ObjectMeta: metav1.ObjectMeta{Name: "new-api", Namespace: "default"},
		Spec:       kipperv1.AppSpec{Image: "api:v2", Port: 8080, Replicas: int32Ptr(1)},
	}
	crClient := testCRClient(frontend, oldAPI, newAPI)
	handler := &RouteGroups{Client: fake.NewClientset(), CRClient: crClient}

	body := `{"host":"app.example.com","mappings":[{"path":"/","app":"frontend"},{"path":"/api","app":"new-api"}]}`
	req := httptest.NewRequest("PUT", "/projects/default/route-groups", strings.NewReader(body))
	rec := httptest.NewRecorder()
	rgRouter(handler).ServeHTTP(rec, req)

	assert.Equal(t, http.StatusOK, rec.Code)

	var updatedOld kipperv1.App
	_ = crClient.Get(context.Background(), crclient.ObjectKey{Namespace: "default", Name: "old-api"}, &updatedOld)
	assert.Nil(t, updatedOld.Spec.Route, "old-api route should be cleared")

	var updatedNew kipperv1.App
	_ = crClient.Get(context.Background(), crclient.ObjectKey{Namespace: "default", Name: "new-api"}, &updatedNew)
	assert.Equal(t, "app.example.com", updatedNew.Spec.Route.Host)
	assert.Equal(t, "/api", updatedNew.Spec.Route.Path)
}

func TestRouteGroups_Delete(t *testing.T) {
	app1 := &kipperv1.App{
		ObjectMeta: metav1.ObjectMeta{Name: "web", Namespace: "default"},
		Spec: kipperv1.AppSpec{
			Image: "nginx", Port: 80, Replicas: int32Ptr(1),
			Route: &kipperv1.AppRoute{Host: "app.example.com", Path: "/"},
		},
	}
	app2 := &kipperv1.App{
		ObjectMeta: metav1.ObjectMeta{Name: "api", Namespace: "default"},
		Spec: kipperv1.AppSpec{
			Image: "api:v1", Port: 8080, Replicas: int32Ptr(1),
			Route: &kipperv1.AppRoute{Host: "app.example.com", Path: "/api"},
		},
	}
	unrelated := &kipperv1.App{
		ObjectMeta: metav1.ObjectMeta{Name: "other", Namespace: "default"},
		Spec: kipperv1.AppSpec{
			Image: "other:v1", Port: 3000, Replicas: int32Ptr(1),
			Route: &kipperv1.AppRoute{Host: "other.example.com", Path: "/"},
		},
	}
	crClient := testCRClient(app1, app2, unrelated)
	handler := &RouteGroups{Client: fake.NewClientset(), CRClient: crClient}

	req := httptest.NewRequest("DELETE", "/projects/default/route-groups/app.example.com", nil)
	rec := httptest.NewRecorder()
	rgRouter(handler).ServeHTTP(rec, req)

	assert.Equal(t, http.StatusNoContent, rec.Code)

	var updated1 kipperv1.App
	_ = crClient.Get(context.Background(), crclient.ObjectKey{Namespace: "default", Name: "web"}, &updated1)
	assert.Nil(t, updated1.Spec.Route)

	var updated2 kipperv1.App
	_ = crClient.Get(context.Background(), crclient.ObjectKey{Namespace: "default", Name: "api"}, &updated2)
	assert.Nil(t, updated2.Spec.Route)

	var updatedOther kipperv1.App
	_ = crClient.Get(context.Background(), crclient.ObjectKey{Namespace: "default", Name: "other"}, &updatedOther)
	assert.Equal(t, "other.example.com", updatedOther.Spec.Route.Host, "unrelated app should be untouched")
}
