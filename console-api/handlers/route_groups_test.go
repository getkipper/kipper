func rgRouter(handler *RouteGroups) *chi.Mux {
	r := chi.NewRouter()
	r.Route("/projects/{name}", func(r chi.Router) {
		r.Post("/route-groups", handler.Create)
		r.Put("/route-groups", handler.Update)
		r.Delete("/route-groups/{host}", handler.Delete)
	})
	return r
}

func TestRouteGroups_Create_AutoGeneratedHost(t *testing.T) {
	ns := &corev1.Namespace{
		ObjectMeta: metav1.ObjectMeta{
			Name:   "staging",
			Labels: map[string]string{"kipper.run/environment": "staging"},
		},
	}
	frontend := &kipperv1.App{
		ObjectMeta: metav1.ObjectMeta{Name: "frontend", Namespace: "staging"},
		Spec:       kipperv1.AppSpec{Image: "nginx", Port: 80, Replicas: int32Ptr(1)},
	}
	api := &kipperv1.App{
		ObjectMeta: metav1.ObjectMeta{Name: "api", Namespace: "staging"},
		Spec:       kipperv1.AppSpec{Image: "api:v1", Port: 8080, Replicas: int32Ptr(1)},
	}
	crClient := testCRClient(frontend, api)
	handler := &RouteGroups{
		Client:   fake.NewClientset(ns),
		CRClient: crClient,
		Domain:   "203-0-113-12.kipper.run",
	}

	body := `{"mappings":[{"path":"/","app":"frontend"},{"path":"/api","app":"api"}]}`
	req := httptest.NewRequest("POST", "/projects/staging/route-groups", strings.NewReader(body))
	rec := httptest.NewRecorder()
	rgRouter(handler).ServeHTTP(rec, req)

	assert.Equal(t, http.StatusOK, rec.Code)
	var resp routeGroupResult
	_ = json.Unmarshal(rec.Body.Bytes(), &resp)
	assert.Equal(t, "frontend-staging--203-0-113-12.kipper.run", resp.Host)
	assert.Len(t, resp.Mappings, 2)

	var updatedFrontend kipperv1.App
	_ = crClient.Get(context.Background(), crclient.ObjectKey{Namespace: "staging", Name: "frontend"}, &updatedFrontend)
	assert.Equal(t, "frontend-staging--203-0-113-12.kipper.run", updatedFrontend.Spec.Route.Host)
	assert.Equal(t, "/", updatedFrontend.Spec.Route.Path)

	var updatedAPI kipperv1.App
	_ = crClient.Get(context.Background(), crclient.ObjectKey{Namespace: "staging", Name: "api"}, &updatedAPI)
	assert.Equal(t, "frontend-staging--203-0-113-12.kipper.run", updatedAPI.Spec.Route.Host)
	assert.Equal(t, "/api", updatedAPI.Spec.Route.Path)
}

