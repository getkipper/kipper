// openPostgresTestDB connects to the server named by KIPPER_TEST_POSTGRES_DSN
// and creates a uniquely named schema that it drops when the test ends.
// The DSN must identify a user allowed to create schemas, for example
// postgres://postgres:pw@127.0.0.1:5432/postgres?sslmode=disable.
func openPostgresTestDB(t *testing.T) (*sql.DB, string) {
	t.Helper()
	dsn := os.Getenv("KIPPER_TEST_POSTGRES_DSN")
	if dsn == "" {
		t.Skip("KIPPER_TEST_POSTGRES_DSN is not set")
	}
	db, err := sql.Open("pgx", dsn)
	if err != nil {
		t.Fatalf("open: %v", err)
	}
	t.Cleanup(func() { _ = db.Close() })

	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()
	schema := fmt.Sprintf("kipper_structure_test_%d", time.Now().UnixNano())
	if _, err := db.ExecContext(ctx, "CREATE SCHEMA "+schema); err != nil {
		t.Fatalf("create schema: %v", err)
	}
	t.Cleanup(func() {
		_, _ = db.ExecContext(context.Background(), "DROP SCHEMA IF EXISTS "+schema+" CASCADE")
	})
	stmts := []string{
		`CREATE TABLE ` + schema + `.users (
			id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
			email TEXT NOT NULL,
			first_name TEXT,
			last_name TEXT,
			full_name TEXT GENERATED ALWAYS AS (first_name || ' ' || last_name) STORED,
			created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
			CONSTRAINT users_email_uq UNIQUE (email)
		)`,
		`CREATE TABLE ` + schema + `.order_lines (
			order_id INT NOT NULL,
			line INT NOT NULL,
			user_id BIGINT NOT NULL REFERENCES ` + schema + `.users (id),
			qty SERIAL,
			ext_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
			PRIMARY KEY (order_id, line)
		)`,
		`CREATE INDEX order_lines_user_idx ON ` + schema + `.order_lines (user_id)`,
	}
	for _, s := range stmts {
		if _, err := db.ExecContext(ctx, s); err != nil {
			t.Fatalf("setup %q: %v", s, err)
		}
	}
	return db, schema
}

func TestReadTableStructurePostgres(t *testing.T) {
	db, schema := openPostgresTestDB(t)
	ctx := context.Background()

	users, err := readTableStructure(ctx, db, "pgx", schema, "users")
	if err != nil {
		t.Fatalf("users structure: %v", err)
	}
	var names []string
	generated := map[string]bool{}
	types := map[string]string{}
	for _, c := range users.Columns {
		names = append(names, c.Name)
		generated[c.Name] = c.Generated
		types[c.Name] = c.Type
	}
	if want := []string{"id", "email", "first_name", "last_name", "full_name", "created_at"}; !slices.Equal(names, want) {
		t.Errorf("users columns = %v, want %v", names, want)
	}
	if !generated["id"] || !generated["full_name"] || generated["created_at"] || generated["email"] {
		t.Errorf("only the identity and the generated column are generated, got %v", generated)
	}
	if types["id"] != "bigint" || types["created_at"] != "timestamp with time zone" {
		t.Errorf("Postgres column types come from data_type, got %v", types)
	}
	if !slices.Equal(users.PrimaryKey, []string{"id"}) {
		t.Errorf("users primary key = %v, want [id]", users.PrimaryKey)
	}
	if !hasIndex(users.Indexes, "users_email_uq", true) || !hasIndex(users.Indexes, "users_pkey", true) {
		t.Errorf("users indexes = %+v, want users_pkey and users_email_uq", users.Indexes)
	}

	lines, err := readTableStructure(ctx, db, "pgx", schema, "order_lines")
	if err != nil {
		t.Fatalf("order_lines structure: %v", err)
	}
	if !slices.Equal(lines.PrimaryKey, []string{"order_id", "line"}) {
		t.Errorf("order_lines primary key = %v, want [order_id line]", lines.PrimaryKey)
	}
	wantFK := fkInfo{Column: "user_id", RefSchema: schema, RefTable: "users", RefColumn: "id"}
	if len(lines.ForeignKeys) != 1 || lines.ForeignKeys[0] != wantFK {
		t.Errorf("order_lines foreign keys = %+v, want [%+v]", lines.ForeignKeys, wantFK)
	}
	for _, c := range lines.Columns {
		if (c.Name == "qty" || c.Name == "ext_id") && c.Generated {
			t.Errorf("%s takes explicit values and is not generated", c.Name)
		}
	}
	if !hasIndex(lines.Indexes, "order_lines_user_idx", false) {
		t.Errorf("order_lines indexes = %+v, want order_lines_user_idx", lines.Indexes)
	}
}

func TestAlterTablePostgres(t *testing.T) {
	db, schema := openPostgresTestDB(t)
	ctx := context.Background()
	ops := []tableOp{
		{Op: "add_column", Column: &columnSpec{Name: "nickname", Type: "text", Nullable: true}},
		{Op: "alter_column_type", Column: &columnSpec{Name: "email", Type: "varchar(320)", Nullable: false}},
		{Op: "set_nullable", Column: &columnSpec{Name: "first_name", Nullable: false}},
		{Op: "set_nullable", Column: &columnSpec{Name: "email", Nullable: true}},
		{Op: "rename_column", OldName: "last_name", NewName: "surname"},
		{Op: "set_default", Column: &columnSpec{Name: "nickname", Default: strPtr("'anon'")}},
		{Op: "drop_column", Name: "nickname"},
	}
	ddl, err := buildAlterTable("pgx", schema, "users", ops, nil)
	if err != nil {
		t.Fatal(err)
	}
	if err := execInTx(ctx, db, ddl); err != nil {
		t.Fatalf("alter: %v", err)
	}
	users, err := readTableStructure(ctx, db, "pgx", schema, "users")
	if err != nil {
		t.Fatal(err)
	}
	cols := map[string]columnInfo{}
	for _, c := range users.Columns {
		cols[c.Name] = c
	}
	if c := cols["email"]; c.Type != "character varying" || !c.Nullable {
		t.Errorf("email = %+v, want nullable character varying", c)
	}
	if c := cols["first_name"]; c.Nullable {
		t.Errorf("first_name = %+v, want NOT NULL", c)
	}
	if _, ok := cols["surname"]; !ok {
		t.Error("last_name should have been renamed to surname")
	}
	if _, ok := cols["nickname"]; ok {
		t.Error("nickname should have been dropped")
	}
	if c := cols["created_at"]; c.Default != "now()" || c.Nullable {
		t.Errorf("created_at = %+v, untouched columns keep their definition", c)
	}

	drop, err := buildDropIndex("pgx", schema, "", "order_lines_user_idx", false)
	if err != nil {
		t.Fatal(err)
	}
	if err := execDDL(ctx, db, drop, false); err != nil {
		t.Fatalf("%s: %v", drop, err)
	}
	lines, err := readTableStructure(ctx, db, "pgx", schema, "order_lines")
	if err != nil {
		t.Fatal(err)
	}
	if hasIndex(lines.Indexes, "order_lines_user_idx", false) {
		t.Errorf("order_lines_user_idx is still present after %s", drop)
	}
}

func TestRowStatementsPostgres(t *testing.T) {
	db, schema := openPostgresTestDB(t)
	ctx := context.Background()
	structure, err := readTableStructure(ctx, db, "pgx", schema, "users")
	if err != nil {
		t.Fatal(err)
	}

	insert := buildInsertReturning("pgx", schema, "users", []string{"email", "first_name", "last_name"}, len(structure.Columns))
	row, err := scanSingleRow(db.QueryRowContext(ctx, insert, "ada@example.com", "Ada", "Lovelace"), structure)
	if err != nil {
		t.Fatalf("%s: %v", insert, err)
	}
	id := row[0]
	if row[4] != "Ada Lovelace" {
		t.Errorf("RETURNING * should carry the generated column, got %v", row)
	}

	update, args := buildUpdate("pgx", schema, "users", []string{"first_name"}, []string{"id"},
		map[string]interface{}{"first_name": "Augusta"}, map[string]interface{}{"id": id})
	if res, err := db.ExecContext(ctx, update, args...); err != nil || affectedOr(res, 0) != 1 {
		t.Fatalf("%s: %v", update, err)
	}

	sel := buildSelectRows("pgx", schema, "users", structure.Columns, "id", "ASC", 10, 0, "email")
	var total int64
	if err := db.QueryRowContext(ctx, buildCountRows("pgx", schema, "users", "email"), "ada@example.com").Scan(&total); err != nil || total != 1 {
		t.Fatalf("count: %v, total %d", err, total)
	}
	rows, err := db.QueryContext(ctx, sel, "ada@example.com")
	if err != nil {
		t.Fatalf("%s: %v", sel, err)
	}
	_ = rows.Close()

	del, args := buildDelete("pgx", schema, "users", []string{"id"}, map[string]interface{}{"id": id})
	if res, err := db.ExecContext(ctx, del, args...); err != nil || affectedOr(res, 0) != 1 {
		t.Fatalf("%s: %v", del, err)
	}
}

func TestReadSchemaPostgres(t *testing.T) {
	db, schema := openPostgresTestDB(t)
	resp, err := readSchema(context.Background(), db, "pgx")
	if err != nil {
		t.Fatal(err)
	}
	if resp.Dialect != "postgres" {
		t.Errorf("dialect = %q, want postgres", resp.Dialect)
	}
	found := false
	for _, d := range resp.Databases {
		for _, s := range d.Schemas {
			if s.Name == schema {
				found = len(s.Relations) > 0
			}
		}
	}
	if !found {
		t.Errorf("schema %s with its tables is missing from %+v", schema, resp.Databases)
	}
}
